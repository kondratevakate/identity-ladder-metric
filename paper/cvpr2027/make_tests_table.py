"""Main-text table: which pixel metrics pass the directional tests T1-T3b in each image set, at window 1/8.

Source: results/cross_modality/tests_f8_v1.json (one-sided Wilcoxon on family/person means, Holm within dataset).
Pass = reference closer than the control after Holm correction; fail = not shown; n/a = test not available.
Usage: python -I paper/cvpr2027/make_tests_table.py   (run from the repository root)
"""
import json

SRC = "results/cross_modality/tests_f8_v1.json"
OUT = "paper/cvpr2027/tab/tests_f8.tex"
METRICS = ["mse", "ssim", "tm_like", "lddt"]
TESTS = ["T1", "T2", "T3a", "T3b"]
PASS, FAIL, NA = r"\cmark", r"\xmark", r"\nmark"

data = json.load(open(SRC, encoding="utf-8"))["datasets"]


def mark(entry):
    """One symbol per test; a missing or empty test is n/a, never a fail."""
    if not entry or "pass" not in entry:
        return NA
    return PASS if entry["pass"] else FAIL


rows = []
for name, item in data.items():
    cells = []
    for metric in METRICS:
        tests = item["tests"].get(metric, {})
        cells.append("".join(mark(tests.get(t)) for t in TESTS))
    ref = "opp." if item["reference"] != "repeat" else "2nd"
    rows.append(" & ".join([name, ref] + cells) + r" \\")

with open(OUT, "w", encoding="utf-8") as fh:
    fh.write("% Generated by paper/cvpr2027/make_tests_table.py from " + SRC + "\n")
    # \bottomrule inside the file: an \input followed by \bottomrule in the tabular breaks \noalign.
    fh.write("\n".join(rows) + "\n\\bottomrule\n")
print(open(OUT, encoding="utf-8").read())
