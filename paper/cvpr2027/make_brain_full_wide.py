"""Full brain profiles as one compact table: one row per distance, one column per rung.

Reads tab/brain_full.tex (long form written by prepare.py from results/donor_ladder_brain_metrics.json:
metric, rung, value with interval, targets, families) and writes tab/brain_full_wide.tex.
The second scan is the anchor (0 by definition) and is left out; the lowest value in each row is bold.

Run from paper/cvpr2027:  python make_brain_full_wide.py
"""
import re
from pathlib import Path

SRC = Path("tab/brain_full.tex")
OUT = Path("tab/brain_full_wide.tex")
ROW = re.compile(r"^(.*?) & (.*?) & \\shortstack\{(-?[\d.]+)\\statuspre\\\\\{\\scriptsize \[(-?[\d.]+), (-?[\d.]+)\]\}\} & (\d+) & (\d+) \\\\$")
ORDER = ["Dataset average", "Opposite side", "Softened second scan", "Wrong detail", "Noise"]


def num(x):
    if float(x) == 0:  # "-0.000" is zero at the printed precision
        return x.lstrip("-")
    return x.replace("-", "$-$")


def main():
    table, counts, metrics = {}, {}, []
    for line in SRC.read_text(encoding="utf8").splitlines():
        m = ROW.match(line.strip())
        if not m and "undefined" in line:  # a rung the distance cannot score: stays an empty cell
            metric = line.split("&")[0].strip()
            if metric not in metrics:
                metrics.append(metric)
            continue
        if not m:
            if line.strip() and not line.startswith("%") and "rule" not in line:
                raise ValueError(f"unparsed row: {line[:80]}")
            continue
        metric, rung, v, lo, hi, targets, families = m.groups()
        if metric not in metrics:
            metrics.append(metric)
        table[(metric, rung)] = (v, lo, hi)
        counts.setdefault(rung, set()).add((targets, families))
    rungs = [r for r in ORDER if any((m, r) in table for m in metrics)]
    unknown = {r for (_, r) in table} - set(ORDER) - {"Second scan"}
    if unknown:
        raise ValueError(f"rungs without a column: {unknown}")
    lines = ["% Generated by paper/cvpr2027/make_brain_full_wide.py from tab/brain_full.tex; do not edit by hand."]
    for metric in metrics:
        vals = {r: float(table[(metric, r)][0]) for r in rungs if (metric, r) in table}
        low = min(vals.values())
        cells = []
        for r in rungs:
            if (metric, r) not in table:
                cells.append("$\\cdot$")
                continue
            v, lo, hi = table[(metric, r)]
            head = num(v)
            if float(v) == low:
                head = "\\textbf{" + head + "}"
            cells.append(f"\\shortstack{{{head}\\\\{{\\scriptsize [{num(lo)}, {num(hi)}]}}}}")
        lines.append(metric + " & " + " & ".join(cells) + " \\\\")
    lines.append("\\bottomrule")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf8", newline="\n")
    print("rows", len(metrics), "columns", rungs)
    for r, c in counts.items():
        print(" ", r, sorted(c))


if __name__ == "__main__":
    main()
