"""Softened control under squared error: predicted against observed position (supplement table).

With the softened fill mean + lambda (f - mean) and lambda = 1 - Q/2, expanding the squared error gives
Q_soft = 1 - lambda (1 + G - Q) + lambda^2 G, where Q is the error of the unchanged second image relative to the
dataset average and G the ratio of the detail energy of the second images to that of the targets. For G = 1 this is
Q_soft = Q (1 - Q/4), so on the random-person scale R_soft = R_same (1 - Q/4) with Q = R_same / R_average.

Source (aggregates only): results/cross_modality/common_f8_v1.json (MSE, hidden region 1/8 of the object).
Writes results/cross_modality/t2_identity_f8_v1.json, paper/cvpr2027/tab/t2_identity.tex and
paper/cvpr2027/tab/t2_identity_numbers.tex. Usage: python -I paper/cvpr2027/make_t2_identity.py (repository root).
"""
import json

SRC = "results/cross_modality/common_f8_v1.json"
OUT = "results/cross_modality/t2_identity_f8_v1.json"
TAB = "paper/cvpr2027/tab/t2_identity.tex"
NUM = "paper/cvpr2027/tab/t2_identity_numbers.tex"

data = json.load(open(SRC, encoding="utf-8"))["datasets"]
rows, out = [], {"method": __doc__.strip(), "metric": "mse", "f": "1/8", "datasets": {}}
for name, e in data.items():
    R = e["R_self"]
    if not all(k in R and "mse" in R[k] for k in ("repeat", "shrink_ref", "dataset_mean")):
        continue                                   # no second image in this set: the control does not exist
    same, soft, avg = (R[k]["mse"][0] for k in ("repeat", "shrink_ref", "dataset_mean"))
    q = same / avg
    lam = 1 - q / 2
    pred = same * (1 - q / 4)
    # G that makes the general formula exact for the observed value: Q_soft = 1 - lam (1 + G - Q) + lam^2 G
    g = (1 - lam * (1 - q) - soft / avg) / (lam - lam ** 2)
    out["datasets"][name] = {"R_same": same, "R_average": avg, "Q": round(q, 4), "lambda": round(lam, 4),
                             "R_soft_predicted_G1": round(pred, 4), "R_soft_observed": soft,
                             "difference": round(soft - pred, 4), "G_implied": round(g, 4)}
    rows.append(f"{name} & {q:.2f} & {lam:.2f} & {same:.3f} & {pred:.3f} & {soft:.3f} & {g:.2f} \\\\")
worst = max(abs(v["difference"]) for v in out["datasets"].values())
out["max_abs_difference"] = round(worst, 4)
with open(OUT, "w", encoding="utf-8") as fh:
    json.dump(out, fh, indent=1)
with open(TAB, "w", encoding="utf-8") as fh:
    fh.write("% Generated by paper/cvpr2027/make_t2_identity.py from " + SRC + "\n" + "\n".join(rows) + "\n\\bottomrule\n")
with open(NUM, "w", encoding="utf-8") as fh:
    fh.write("% Generated by paper/cvpr2027/make_t2_identity.py; do not edit.\n"
             "\\newcommand{\\tTwoMaxDiff}{" + f"{worst:.3f}" + "}\n"
             "\\newcommand{\\tTwoSets}{" + str(len(rows)) + "}\n")
print("\n".join(rows))
print("max abs difference", worst)
