"""Table and figure: pretrained inpainting models on the identity ladder (hidden region = 1/8 of the object).

Sources (aggregates only): results/model_fills_v1/model_fills_f8.json (R on the random-person scale, from
src/model_fills_summary.py) and results/model_fills_v1/model_fills_face_panel.json (LPIPS, FID, FWD at the 16 px
panel window, from src/model_fills_face_panel.py). A model that was not run is printed as n/a, never as a value.

Also read: model_fills_size_faces.json (size curve) and model_fills_input_sensitivity.json (input construction).

Writes paper/cvpr2027/tab/model_fills{,_full,_size,_input,_numbers}.tex, fig/model_fills_v1.{pdf,png} and
fig/model_fills_v1_plotted.json.
Usage: python -I paper/cvpr2027/make_model_fills.py   (run from the repository root)
"""
import json
import os
import sys

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fig_style as S  # noqa: E402

F8 = "results/model_fills_v1/model_fills_f8.json"
PANEL = "results/model_fills_v1/model_fills_face_panel.json"
TAB = "paper/cvpr2027/tab/model_fills.tex"
FIG = "paper/cvpr2027/fig/model_fills_v1"
DATASETS = ["QTIM", "CelebA", "IMDb-WIKI"]
METRICS = [("mse", "MSE"), ("ssim", "SSIM"), ("lddt", "lDDT-like")]
REFS = [("repeat", "ref"), ("shrink_ref", "shrink_ref"), ("lookalike16", "lookalike16"), ("dataset_mean", "dataset_mean")]
MODELS = [("brats24_unet", "BraTS 2024 winner", "#111111", "*"), ("lama_celebahq", "LaMa (CelebA-HQ)", "#111111", "*"),
          ("lama_places", "LaMa (Places)", "#7a7a7a", "*"), ("sd15_inpaint", "Stable Diffusion 1.5", "#8b1a1a", "p")]

f8 = json.load(open(F8, encoding="utf-8"))["datasets"]
panel = json.load(open(PANEL, encoding="utf-8"))["datasets"] if os.path.exists(PANEL) else {}


def ref_value(ds, rung, m):
    v = f8[ds]["references"].get(rung, {}).get(m)
    return v


def model_entry(ds, key):
    e = f8[ds]["models"].get(key)
    return None if e is None or "status" in e else e


def num(v, nd=2):
    return "n/a" if v is None else f"{v:.{nd}f}"


# ---------------------------------------------------------------------------------------------------- table
TAB_FULL = "paper/cvpr2027/tab/model_fills_full.tex"
STORED_FID = {"repeat": "repeat", "shrink_ref": "shrink_repeat", "dataset_mean": "dataset_mean"}


def set_ratio(ds, key=None, rung=None, what="fid"):
    """Set distance over the random-person set's distance at the 16 px panel window (faces only)."""
    pv = panel.get(ds, {})
    if key is not None:
        return pv.get("models", {}).get(key, {}).get("set_level", {}).get(f"{what}_over_random_person")
    sr = pv.get("set_level_references_stored", {}).get(STORED_FID.get(rung, ""))
    return sr[f"{what}_over_random_person"] if sr else None


MAIN_TABLE_WITH_FID = False


def table():
    """Main-text table (the whole tabular): MSE and SSIM on the random-person scale at 1/8. The set-level column is
    off: the main text was frozen on 17 Nov 2026 without it, and FID and FWD of the models are in the supplement table
    (MAIN_TABLE_WITH_FID turns the column on)."""
    with_fid = MAIN_TABLE_WITH_FID and any("set_level" in m for d in panel.values() for m in d.get("models", {}).values())
    lines = ["% Generated by paper/cvpr2027/make_model_fills.py from " + F8 + (" and " + PANEL if with_fid else "")]
    face_cols = ["MSE", "SSIM"] + (["FID"] if with_fid else [])
    nf = len(face_cols)
    lines.append(r"\begin{tabular}{@{}l" + "r" * (2 + 2 * nf) + "@{}}")
    lines.append(r"\toprule")
    lines.append(r" & \multicolumn{2}{c}{QTIM} & \multicolumn{%d}{c}{CelebA} & \multicolumn{%d}{c}{IMDb-WIKI} \\"
                 % (nf, nf))
    lines.append(r"\cmidrule(lr){2-3}\cmidrule(lr){4-%d}\cmidrule(l){%d-%d}" % (3 + nf, 4 + nf, 3 + 2 * nf))
    lines.append("Fill & " + " & ".join(r"\acs{" + c + "}" for c in ["MSE", "SSIM"] + face_cols * 2) + r" \\")
    lines.append(r"\midrule")

    def row(name, getter, fid):
        cells = [name]
        for ds in DATASETS:
            for m in ("mse", "ssim"):
                v = getter(ds, m)
                cells.append(num(v[0] if v else None))
            if ds != "QTIM" and with_fid:
                cells.append(num(fid(ds), 1))
        return " & ".join(cells) + r" \\"
    for rung, style in REFS:
        lines.append(row(S.label(style).capitalize(), lambda ds, m, r=rung: ref_value(ds, r, m),
                         lambda ds, r=rung: set_ratio(ds, rung=r)))
    lines.append(r"\midrule")
    notes = []
    for key, name, _, _ in MODELS:
        entries = {ds: model_entry(ds, key) for ds in DATASETS}
        if not any(entries.values()):
            continue
        sub = [ds for ds, e in entries.items() if e and e["n_targets"] < e["n_targets_dataset"]]
        notes += [f"{name}, {ds}: {entries[ds]['n_targets']} of {entries[ds]['n_targets_dataset']} targets" for ds in sub]
        lines.append(row(name + (r"$^{\dagger}$" if sub else ""),
                         lambda ds, m, en=entries: en[ds]["R_self"].get(m) if en[ds] else None,
                         lambda ds, k=key: set_ratio(ds, key=k)))
    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}")
    lines.append("% subsets: " + "; ".join(notes))
    with open(TAB, "w", encoding="utf-8") as fh:
        fh.write(chr(10).join(lines) + chr(10))
    print(chr(10).join(lines))

    # supplement: one row per model and dataset, every metric, references recomputed on the model's own targets
    full = ["% Generated by paper/cvpr2027/make_model_fills.py from " + F8 + " and " + PANEL]
    for ds in DATASETS:
        for key, name, _, _ in MODELS:
            e = model_entry(ds, key)
            if not e:
                continue
            R, ref = e["R_self"], e["references_same_targets"]
            pm = panel.get(ds, {}).get("models", {}).get(key, {})
            lp = pm.get("lpips_alex", {}).get("R_self_model")
            cells = [ds, name, f"{e['n_targets']} of {e['n_targets_dataset']}",
                     f"{R['mse'][0]:.3f} [{R['mse'][1]:.3f}, {R['mse'][2]:.3f}]"]
            cells += [num(R[m][0]) if m in R else "n/a" for m in ("ssim", "tm_like", "gdt_like", "lddt")]
            cells += [num(ref[r]["mse"][0]) if r in ref and "mse" in ref[r] else "n/a"
                      for r in ("repeat", "shrink_ref", "lookalike16", "dataset_mean")]
            cells += [num(lp[0] if lp else None), num(set_ratio(ds, key=key), 1),
                      num(set_ratio(ds, key=key, what="fwd"), 1)]
            full.append(" & ".join(cells) + r" \\")
    full.append(r"\bottomrule")
    with open(TAB_FULL, "w", encoding="utf-8") as fh:
        fh.write("\n".join(full) + "\n")
    print("\n".join(full))


# --------------------------------------------------------------------------------------------------- figure
def figure():
    """One panel per image set, fixed lanes shared by the panels (references above, models below), so no label can
    collide with a marker; the value is printed next to each marker and a dagger marks a subset of targets."""
    S.apply()
    lanes = [(S.label(style).capitalize(), ("ref", rung), S.color(style), S.marker(style), S.MS) for rung, style in REFS]
    n_ref = len(lanes)
    lanes += [(name, ("model", key), col, mk, 6.5) for key, name, col, mk in MODELS
              if any(model_entry(ds, key) for ds in DATASETS)]
    fig, axes = plt.subplots(1, 3, figsize=(S.TEXTWIDTH_IN, 0.42 + 0.21 * len(lanes)), sharex=True, sharey=True)
    plotted = {}
    for ax, ds in zip(axes, DATASETS):
        plotted[ds] = {}
        n_all = None
        for y, (lab, (kind, key), col, mk, ms) in enumerate(lanes):
            dagger = ""
            if kind == "ref":
                v = ref_value(ds, key, "mse")
            else:
                e = model_entry(ds, key)
                v = e["R_self"].get("mse") if e else None
                if e:
                    n_all = e["n_targets_dataset"]
                    dagger = "†" if e["n_targets"] < e["n_targets_dataset"] else ""
            if not v:
                continue
            ax.plot([v[1], v[2]], [y, y], color=col, lw=1.0, solid_capstyle="butt")
            ax.plot(v[0], y, marker=mk, ms=ms, color=col, mec="white", mew=S.EDGE, ls="")
            ax.text(v[2] + 0.04, y, f"{v[0]:.2f}{dagger}", va="center", ha="left", fontsize=S.SIZE_SMALL, color=S.INK)
            plotted[ds][lab] = v[:3]
        ax.axvline(1.0, color=S.color("stranger"), lw=0.8, ls=(0, (2, 2)))
        ax.axvline(0.0, color=S.RULE, lw=0.8)
        ax.axhline(n_ref - 0.5, color=S.RULE, lw=0.6)
        ax.set_ylim(len(lanes) - 0.4, -0.6)
        ax.set_xlim(-0.04, 1.12)
        ax.set_xticks([0, 0.5, 1.0])
        ax.set_xticklabels(["0", "0.5", "1"])
        ax.tick_params(axis="y", length=0)
        for sp in ("top", "right", "left"):
            ax.spines[sp].set_visible(False)
        n = n_all if n_all else f8[ds]["n_units"]
        ax.set_title(f"{ds}  ({n} people)", fontsize=S.SIZE_TITLE, fontweight="bold", loc="left")
    axes[0].set_yticks(range(len(lanes)))
    axes[0].set_yticklabels([lane[0] for lane in lanes], fontsize=S.SIZE_SMALL)
    fig.supxlabel("MSE on the random-person scale: 0 = target, 1 = random person (hidden region = 1/8 of the object)",
                  fontsize=S.SIZE, y=0.0)
    fig.subplots_adjust(left=0.19, right=0.992, top=0.88, bottom=0.24, wspace=0.07)
    fig.savefig(FIG + ".pdf")
    fig.savefig(FIG + ".png", dpi=300)
    json.dump(plotted, open(FIG + "_plotted.json", "w", encoding="utf-8"), indent=1)
    print(FIG + ".pdf")


# --------------------------------------------------------------------------------------------------- macros
NUM = "paper/cvpr2027/tab/model_fills_numbers.tex"
SIZE = "results/model_fills_v1/model_fills_size_faces.json"
TAB_SIZE = "paper/cvpr2027/tab/model_fills_size.tex"
size = json.load(open(SIZE, encoding="utf-8"))["datasets"] if os.path.exists(SIZE) else {}
SENS = "results/model_fills_v1/model_fills_input_sensitivity.json"
TAB_SENS = "paper/cvpr2027/tab/model_fills_input.tex"
sens = json.load(open(SENS, encoding="utf-8"))["datasets"] if os.path.exists(SENS) else {}
MODEL_TAG = {"lama_places": "LamaPlaces", "lama_celebahq": "LamaHq", "sd15_inpaint": "Sd", "brats24_unet": "Brats"}
DS_TAG = {"QTIM": "Qtim", "CelebA": "Celeba", "IMDb-WIKI": "Imdb"}
MET_TAG = {"mse": "Mse", "ssim": "Ssim", "lddt": "Lddt", "tm_like": "Tm", "gdt_like": "Gdt"}
RUNG_TAG = {"repeat": "Repeat", "dataset_mean": "Mean", "lookalike16": "Nearest", "shrink_ref": "Soft"}


def macros():
    """One LaTeX macro per number quoted in the text, so the text cannot drift from the results files."""
    out = ["% Generated by paper/cvpr2027/make_model_fills.py from " + F8 + " and " + PANEL + "; do not edit."]

    def put(name, text):
        out.append("\\newcommand{\\mf" + name + "}{" + text + "}")
    for key, mt in MODEL_TAG.items():
        for ds, dt in DS_TAG.items():
            if key not in f8[ds]["models"]:
                continue
            e = model_entry(ds, key)
            put(f"{mt}{dt}N", str(e["n_targets"]) if e else "n/a")
            det = e.get("detail_norm_ratio_median", {}) if e else {}
            for k, tag in (("model", "Detail"), ("repeat", "RefRepeatDetail"), ("lookalike16", "RefNearestDetail")):
                put(f"{mt}{dt}{tag}", num(det.get(k)))
            for ref, rt in (("repeat", "Repeat"), ("lookalike16", "Nearest"), ("dataset_mean", "Mean")):
                dv = e["model_minus_reference"].get(ref, {}).get("mse") if e else None
                put(f"{mt}{dt}Minus{rt}Mse", f"{dv[0]:+.2f}".replace("-", "$-$").replace("+", "$+$") if dv else "n/a")
                put(f"{mt}{dt}Minus{rt}MseCi", f"[{dv[1]:.2f}, {dv[2]:.2f}]" if dv else "n/a")
                if ref == "lookalike16":      # how far the model is ahead of the mean of the 16 nearest people
                    put(f"{mt}{dt}AheadNearest", f"{-dv[0]:.2f}" if dv else "n/a")
            for m, tt in MET_TAG.items():
                v = e["R_self"].get(m) if e else None
                put(f"{mt}{dt}{tt}", num(v[0] if v else None))
                put(f"{mt}{dt}{tt}Ci", f"[{v[1]:.3f}, {v[2]:.3f}]" if v else "n/a")
                for rung, rt in RUNG_TAG.items():
                    rv = e["references_same_targets"].get(rung, {}).get(m) if e else None
                    put(f"{mt}{dt}Ref{rt}{tt}", num(rv[0] if rv else None))
            pm = panel.get(ds, {}).get("models", {}).get(key, {})
            if ds != "QTIM":
                lp = pm.get("lpips_alex", {}).get("R_self_model")
                sl = pm.get("set_level", {})
                put(f"{mt}{dt}Lpips", num(lp[0] if lp else None))
                put(f"{mt}{dt}Fid", num(sl.get("fid_over_random_person"), 1))
                put(f"{mt}{dt}Fwd", num(sl.get("fwd_over_random_person"), 1))
                put(f"{mt}{dt}SetN", str(sl["n_cells"]) if sl else "n/a")
                lref = pm.get("lpips_alex", {}).get("R_self_references_same_targets", {})
                for rk, rt in (("repeat", "Repeat"), ("shrink_ref", "Soft"), ("lookalike_oracle", "Best")):
                    put(f"{mt}{dt}Ref{rt}Lpips", num(lref[rk][0] if rk in lref else None))
    # ranges over the face models and both face sets, for sentences that speak about all of them at once
    face = [e for ds in ("CelebA", "IMDb-WIKI") for key in MODEL_TAG if (e := model_entry(ds, key))]
    ahead = [-e["model_minus_reference"]["lookalike16"]["mse"][0] for e in face]
    detail = [e["detail_norm_ratio_median"]["model"] for e in face if "detail_norm_ratio_median" in e]
    put("FaceAheadMin", num(min(ahead)) if ahead else "n/a")
    put("FaceAheadMax", num(max(ahead)) if ahead else "n/a")
    put("FaceDetailMin", num(min(detail)) if detail else "n/a")
    put("FaceDetailMax", num(max(detail)) if detail else "n/a")
    pm_all = [m for ds in ("CelebA", "IMDb-WIKI") for m in panel.get(ds, {}).get("models", {}).values()]
    for what, tag, nd in (("fid_over_random_person", "Fid", 1), ("fwd_over_random_person", "Fwd", 1)):
        vals = [m["set_level"][what] for m in pm_all if "set_level" in m]
        put(f"Face{tag}Min", num(min(vals), nd) if vals else "n/a")
        put(f"Face{tag}Max", num(max(vals), nd) if vals else "n/a")
    lps = [m["lpips_alex"]["R_self_model"][0] for m in pm_all if m.get("lpips_alex", {}).get("R_self_model")]
    put("FaceLpipsMin", num(min(lps)) if lps else "n/a")
    put("FaceLpipsMax", num(max(lps)) if lps else "n/a")
    for ds, dt in DS_TAG.items():
        if ds == "QTIM" or ds not in panel:
            continue
        for k, rt in (("repeat", "Repeat"), ("dataset_mean", "Mean"), ("shrink_repeat", "Soft"), ("wrong_detail", "Wrong")):
            sr = panel[ds].get("set_level_references_stored", {}).get(k)
            put(f"Ref{dt}{rt}Fid", num(sr["fid_over_random_person"] if sr else None, 1))
            put(f"Ref{dt}{rt}Fwd", num(sr["fwd_over_random_person"] if sr else None, 1))
    # size curve of the face models (F3 subset): model and reference values per window
    words = {5: "Five", 10: "Ten", 16: "Sixteen", 20: "Twenty"}
    size_rows = ["% Generated by paper/cvpr2027/make_model_fills.py from " + SIZE]
    for ds in ("CelebA", "IMDb-WIKI"):
        pts = size.get(ds, {})
        by_w = {v["window_px"]: v for v in pts.values()}
        fills = ([("LaMa (CelebA-HQ)", "models", "lama_celebahq", "LamaHq"), ("LaMa (Places)", "models", "lama_places", "LamaPlaces"),
                  ("16 nearest people", "references", "lookalike16", "RefNearest"),
                  ("Dataset average", "references", "dataset_mean", "RefMean"),
                  ("Same person", "references", "repeat", "RefRepeat")])
        for lab, grp, key, tag in fills:
            cells = [ds, lab]
            for w in (5, 10, 16, 20):
                v = by_w.get(w, {}).get(grp, {}).get(key)
                cells.append(num(v[0] if v else None))
                put(f"Size{tag}{DS_TAG[ds]}{words[w]}", num(v[0] if v else None))
            size_rows.append(" & ".join(cells) + " \\\\")
        if ds == "CelebA":
            size_rows.append("\\midrule")
    size_rows.append("\\bottomrule")
    with open(TAB_SIZE, "w", encoding="utf-8") as fh:
        fh.write("\n".join(size_rows) + "\n")
    print("\n".join(size_rows))
    # sensitivity to the way the masked frame is brought to the model resolution (faces, f = 1/8)
    sens_rows = ["% Generated by paper/cvpr2027/make_model_fills.py from " + SENS]
    vtag = {"norm": "Norm", "nearest": "Nearest", "native": "Native", "v2_prefill": "Vtwo", "v1_leak": "Vone"}
    for ds in ("CelebA", "IMDb-WIKI"):
        for key, name in (("lama_celebahq", "LaMa (CelebA-HQ)"), ("lama_places", "LaMa (Places)")):
            e = sens.get(ds, {}).get(key, {})
            var = e.get("variants", {})
            if not var:
                continue
            cells = [ds, name, str(e["n_targets"])]
            for v in ("norm", "nearest", "native", "v2_prefill", "v1_leak"):
                r = var.get(v, {}).get("R_self", {}).get("mse")
                cells.append(num(r[0] if r else None))
                put(f"Sens{MODEL_TAG[key]}{DS_TAG[ds]}{vtag[v]}", num(r[0] if r else None))
            near = e["references_same_targets"].get("lookalike16", {}).get("mse")
            cells.append(num(near[0] if near else None))
            put(f"Sens{MODEL_TAG[key]}{DS_TAG[ds]}N", str(e["n_targets"]))
            sens_rows.append(" & ".join(cells) + " \\\\")
        if ds == "CelebA" and len(sens_rows) > 1:
            sens_rows.append("\\midrule")
    if len(sens_rows) == 1:                                      # a rule cannot open an \input inside a tabular
        sens_rows.append("n/a & not finished & & & & & & & \\\\")
    spread =[abs(e["variants"][v]["R_self"]["mse"][0] - e["variants"]["norm"]["R_self"]["mse"][0])
              for d in sens.values() for e in d.values() if "variants" in e and "norm" in e["variants"]
              for v in ("nearest", "native") if v in e["variants"]]
    put("SensSpread", num(max(spread)) if spread else "n/a")     # largest |alternative - reported| over models and sets
    sens_rows.append("\\bottomrule")
    with open(TAB_SENS, "w", encoding="utf-8") as fh:
        fh.write("\n".join(sens_rows) + "\n")
    print("\n".join(sens_rows))
    with open(NUM, "w", encoding="utf-8") as fh:
        fh.write("\n".join(out) + "\n")
    print(NUM, len(out) - 1, "macros")


table()
figure()
macros()
