"""Supplement table: RQ4 look-alike distance by hidden-region size, one row per image set.

Source: results/rq4_window_size.json (R_self under MSE). A size that was not run is printed as a dot, never as zero.
Usage: python -I paper/cvpr2027/make_rq4_size_table.py   (run from the repository root)
"""
import json

SRC = "results/rq4_window_size.json"
OUT = "paper/cvpr2027/tab/rq4_size_table.tex"
FRACTIONS = [1 / 16, 1 / 8, 1 / 5, 1 / 4]

data = json.load(open(SRC, encoding="utf-8"))["datasets"]


def cell(points, f, rung):
    """Value at the window closest to fraction f (within 15 %), else n/a."""
    if not points:
        return "$\\cdot$"
    near = min(points, key=lambda p: abs(p - f))
    if abs(near - f) > 0.15 * f or not points[near].get(rung):
        return "$\\cdot$"
    return f"{points[near][rung][0]:.2f}"


rows = []
for name, entry in data.items():
    points = {x["f"]: x["R_self_mse"] for x in entry.values() if isinstance(x, dict) and "R_self_mse" in x}
    single = [cell(points, f, "lookalike") for f in FRACTIONS]
    mean16 = [cell(points, f, "lookalike16") for f in FRACTIONS]
    rows.append(" & ".join([name] + single + mean16 + [cell(points, 1 / 8, "dataset_mean")]) + r" \\")

with open(OUT, "w", encoding="utf-8") as fh:
    fh.write("% Generated by paper/cvpr2027/make_rq4_size_table.py from " + SRC + "\n")
    # \bottomrule goes inside the file: an \input followed by \bottomrule in the tabular breaks \noalign.
    fh.write("\n".join(rows) + "\n\\bottomrule\n")
print(open(OUT, encoding="utf-8").read())
